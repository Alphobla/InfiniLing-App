def get_starter_words(language: str, difficulty: str = None) -> list:
    """
    Get starter words for a language.

    Args:
        language: Language code (es, fr, en, de)
        difficulty: Optional CEFR level (A1, A2, B1, B2, C1, C2)

    Returns:
        List of word dictionaries, or all words if no difficulty specified
    """
    lang_words = STARTER_WORDS.get(language, {})

    if not lang_words:
        return []

    if difficulty:
        return lang_words.get(difficulty, [])

    # Return all words for the language
    all_words = []
    for level in ["A1", "A2", "B1", "B2", "C1", "C2"]:
        all_words.extend(lang_words.get(level, []))
    return all_words


def get_supported_languages() -> list:
    """Get list of languages with starter words."""
    return list(STARTER_WORDS.keys())


def get_difficulty_levels() -> list:
    """Get list of CEFR difficulty levels."""
    return ["A1", "A2", "B1", "B2", "C1", "C2"]
